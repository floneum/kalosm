/// A single output row over a Q5-family weight, at the **narrowed** row
/// geometry its 22/24-byte blocks need.
///
/// This rule used to mint [`ScheduleDomain::Point`], and `geom_for` maps
/// `SchedPoint::Point` to `QGeom::Workgroup` — so the narrowed shape the rule
/// is named after was unreachable from the schedule it declared, and the rule
/// was a duplicate of the workgroup catch-all. [`q5_row_domain`] mints the
/// only points that reach it.
pub fn qmm_q5_small_single_row(
    b: &mut Builder<'_>,
    id: Id,
    node: &Node,
    f: &Facts<'_>,
) -> Option<Id> {
    let p = qparts(b, node, f)?;
    if !p.m.known_eq(Dim::Const(1)) || !is_q5_family(p.fmt) {
        return None;
    }
    let cx = DomainCtx::new(f.caps(), default_planner());
    let dom = q5_row_domain(p.fmt, p.n, &cx);
    if dom.params.is_empty() {
        return None;
    }
    mint(b, id, p, ScheduleDomain::Sgemv(dom))
}

/// A single output row: the quantized gemv family.
///
/// The domain is [`qrow_domain`]'s, not the dense `sgemv_domain`'s: a row
/// body gives one workgroup one output row and reaches `block * cols`
/// columns, so a point offered at a wider `n` names a launch that never
/// writes the rest. The dense domain has no such predicate because a dense
/// gemv chunks the output; this one must.
pub fn qmm_single_row(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let p = qparts(b, node, f)?;
    if !p.m.known_eq(Dim::Const(1)) {
        return None;
    }
    let cx = DomainCtx::new(f.caps(), default_planner());
    let dom = qrow_domain(p.fmt, p.n, &cx);
    if dom.params.is_empty() {
        return None;
    }
    mint(b, id, p, ScheduleDomain::Sgemv(dom))
}

/// The wide Q8 tile. `N >= 8192` and `storage >= 32 KiB` were routing
/// thresholds in the reference; both are cost terms now.
pub fn qmm_q8_wide_64x128(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let p = qparts(b, node, f)?;
    if !is_q8_family(p.fmt) || !tile_guard(&p, 64, 1, 128) {
        return None;
    }
    let sched = exact_tile_sched(&p, f)?;
    mint(b, id, p, sched)
}

