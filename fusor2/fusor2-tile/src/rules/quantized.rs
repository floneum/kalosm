    /// The boundary [`qrepack`] is disabled at, asserted rather than asserted
    /// away.
    ///
    /// The rule is bidirectional and correct as a *rewrite*; what is missing is
    /// the launch that produces the repacked byte image, so the operand it
    /// mints names a packing the buffer does not have. Every weight therefore
    /// keeps exactly the layout its leaf carries. When a repack launch lands,
    /// this test fails and `qrepack`'s early return comes out with it.
    #[test]
    fn qrepack_needs_a_repack_launch_that_does_not_exist() {
        let (fx, c) = build(128, 1024, 4096, QFmt::Q6K);
        let nodes = qnodes(&fx, c);
        assert!(
            nodes
                .iter()
                .any(|n| matches!(n, L1::KQContract { layout: QLayout::Native, .. })),
            "the native operand must survive"
        );
        assert!(
            !nodes
                .iter()
                .any(|n| matches!(n, L1::KQContract { layout: QLayout::F32Scales, .. })),
            "no alternative may claim a packing the buffer does not hold"
        );
        assert!(
            !nodes
                .iter()
                .any(|n| matches!(n, L1::KQContract { b, .. } if !matches!(b.access, AccessPlan::Alias))),
            "a quantized weight operand may only alias while nothing repacks it"
        );

        // And the reverse direction is equally absent: an F32Scales weight
        // keeps F32Scales.
        let mut fx = Fixture::new(apple_caps());
        let act = fx.buffer(Dtype::F32, &[128, 1024]);
        let w = fx.quantized(QFmt::Q6K, QLayout::F32Scales, &[4096, 1024]);
        let c = fx.contract(qspec(), Dtype::F32, act, w);
        fx.apply_all(TILE_RULES, c);
        let nodes = qnodes(&fx, c);
        assert!(
            !nodes
                .iter()
                .any(|n| matches!(n, L1::KQContract { layout: QLayout::Native, .. })),
            "an F32Scales Q6K operand must not mint a Native alternative yet"
        );
    }

