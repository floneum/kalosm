/// The exactly-tiled alternative for every format the Q4K decoder does not
/// own.
pub fn qmm_tile_64x64_cached(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let p = qparts(b, node, f)?;
    if p.fmt == QFmt::Q4K || !tile_guard(&p, 64, 32, 64) {
        return None;
    }
    let sched = exact_tile_sched(&p, f)?;
    mint(b, id, p, sched)
}

/// Q4K's narrower requirement: its 256-element super-blocks reach the exact
/// alternative at a looser column divisibility than the other formats.
pub fn qmm_tile_64x32_q4k(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let p = qparts(b, node, f)?;
    if p.fmt != QFmt::Q4K || !tile_guard(&p, 64, 32, 32) {
        return None;
    }
    let sched = exact_tile_sched(&p, f)?;
    mint(b, id, p, sched)
}

/// The tiled alternative with no divisibility requirement — edge lanes mask.
/// This is what makes N = 8191 land next to N = 8192 instead of several arms
/// down a first-match list: its domain is a pure function of the device and
/// the output extent, so a prime `n` loses the *exact* alternative and not a
/// single geometry.
pub fn qmm_tile_64x64(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let p = qparts(b, node, f)?;
    if !p.m.at_least(2) {
        return None;
    }
    let sched = tile_sched(&p, f)?;
    mint(b, id, p, sched)
}

/// The catch-all: a workgroup-wide fold over K, legal everywhere.
pub fn qmm_workgroup(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let p = qparts(b, node, f)?;
    let cx = DomainCtx::new(f.caps(), default_planner());
    let sched = ScheduleDomain::Fold(fold_domain(p.k, &cx));
    mint(b, id, p, sched)
}

