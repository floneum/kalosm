struct QParts {
    fmt: QFmt,
    layout: QLayout,
    m: Dim,
    n: Dim,
    k: Dim,
    acc: Dtype,
    act: Operand,
    weight: Operand,
}

/// The `QLayout` a value carries, when it is a quantized leaf.
fn leaf_layout(b: &Builder<'_>, id: Id) -> Option<QLayout> {
    match &b.node(id).op {
        Op::L0(L0::Leaf(LeafKind::Quantized { layout, .. })) => Some(*layout),
        _ => None,
    }
}

/// The label partition [`L1::KQContract`] can address.
///
/// The node records three **extents** — [`contract_mnk`] takes the products
/// of the m, n and k labels — and its operands are plain contiguous layouts
/// ([`alias`]). Both backends read the activation at `row * k + kk` and start
/// the weight's block stream at `col * k`, so the node describes
/// `a = [m.., k..]`, `b = [n.., k..]`, `out = [m.., n..]` and nothing else:
/// once the labels are gone, a spec in any other axis order is
/// indistinguishable from the canonical one.
///
/// `mat_mul_transposed_rhs` is canonical. Its `d_lhs` is not — the adjoint
/// spec is `[m, n] x [n, k] -> [m, k]`, so the weight's contracted label is
/// its *first* axis and the block stream gets walked with `[k, rows]`
/// strides. Measured on both backends, bit-identically: for a `[3, 32]`
/// weight the gradient came back as `d_a[t] = sum_j W_flat[3 * t + j]`, the
/// weight read as `[32, 3]`.
///
/// Declining leaves the contraction to `lower_contract_generic`, whose
/// operands carry one explicit stride per label and which computes the
/// adjoint correctly. Teaching `KQContract` a transposed weight means
/// carrying the block axis on the node and honouring it in both backends'
/// block addressing; the floor already has the answer.
///
/// The quantized twin of `contract::canonical_for_mnk`, and it additionally
/// rejects a batch label: `KQContract` has no batch extent, so a batched
/// spec would drop every batch but the first.
fn canonical_for_kq(spec: &EinSpec, weight_is_rhs: bool) -> bool {
    let Ok(part) = partition(spec) else {
        return false;
    };
    if !part.batch.is_empty() || part.k.is_empty() {
        return false;
    }
    let cat = |x: &[Label], y: &[Label]| -> SmallVec<[Label; 8]> {
        x.iter().chain(y).copied().collect()
    };
    // `a` free-then-contracted, `b` free-then-contracted, and the output in
    // the order the kernel writes it: the activation's free axes index the
    // row, the weight's the column.
    if spec.a[..] != cat(&part.m, &part.k)[..] || spec.b[..] != cat(&part.n, &part.k)[..] {
        return false;
    }
    if weight_is_rhs {
        spec.out[..] == cat(&part.m, &part.n)[..]
    } else {
        spec.out[..] == cat(&part.n, &part.m)[..]
    }
}

fn qparts(b: &Builder<'_>, node: &Node, f: &Facts<'_>) -> Option<QParts> {
    let Op::L0(L0::Contract { spec, acc, a, b: rhs, .. }) = &node.op else {
        return None;
    };
    let (fa, fb) = (f.operand(0)?, f.operand(1)?);
    let mnk = contract_mnk(spec, fa, fb);

    // `a` is the activation, `b` the quantized weight — whichever slot the
    // frontend put it in. The activation is read as dense floats, so two
    // quantized operands are nobody's kernel.
    let (fmt, weight_is_rhs, weight_id, weight_facts, act_id, act_facts, m, n) =
        match (fa.dtype, fb.dtype) {
            (Dtype::Q(_), Dtype::Q(_)) => return None,
            (_, Dtype::Q(fmt)) => (fmt, true, *rhs, fb, *a, fa, mnk.m, mnk.n),
            (Dtype::Q(fmt), _) => (fmt, false, *a, fa, *rhs, fb, mnk.n, mnk.m),
            _ => return None,
        };
    if !canonical_for_kq(spec, weight_is_rhs) {
        return None;
    }
    let layout = leaf_layout(b, weight_id).unwrap_or(QLayout::Native);
    Some(QParts {
        fmt,
        layout,
        m,
        n,
        k: mnk.k,
        acc: *acc,
        act: alias(act_id, act_facts),
        weight: alias(weight_id, weight_facts),
    })
}

fn mint(b: &mut Builder<'_>, id: Id, p: QParts, sched: ScheduleDomain) -> Option<Id> {
    let op = L1::KQContract {
        fmt: p.fmt,
        layout: p.layout,
        act: QAct::F32,
        m: p.m,
        n: p.n,
        k: p.k,
        acc: p.acc,
        post: identity(p.acc),
        a: p.act,
        b: p.weight,
        sched,
    };
    let new = b.add_l1(op).ok()?;
    b.union(id, new).ok()?;
    Some(new)
}

/// The tile family's schedule domain: every `(block, cols)` this device can
/// launch on this shape, generated by [`qtile_domain`]. `None` when the
/// domain is empty, which makes the rule decline rather than mint a node
/// nothing could select.
///
/// The reference's `qmatmul_coop_tile_supported` gate — fixed subgroups plus
/// an `F32F32M8N8K8` cooperative configuration — is **deleted**, because the
/// quantized body runs no cooperative MMA: it is one accumulator per lane per
/// column and a loop over the weight's blocks. Requiring coop hardware for it
/// disqualified devices that can run it perfectly well.
fn tile_sched(p: &QParts, f: &Facts<'_>) -> Option<ScheduleDomain> {
    let cx = DomainCtx::new(f.caps(), default_planner());
    let dom = qtile_domain(p.m, p.n, p.acc, &cx);
    (!dom.params.is_empty()).then_some(ScheduleDomain::Sgemm(dom))
}

/// The same domain narrowed to the points that tile this shape exactly — no
/// masked lane, no repeated column. What the divisibility-guarded rules
/// offer, and always a subset of [`tile_sched`]'s.
fn exact_tile_sched(p: &QParts, f: &Facts<'_>) -> Option<ScheduleDomain> {
    let cx = DomainCtx::new(f.caps(), default_planner());
    let dom = qtile_exact_domain(p.m, p.n, p.acc, &cx);
    (!dom.params.is_empty()).then_some(ScheduleDomain::Sgemm(dom))
}

/// Every tile rule additionally needs more than one row: a single-row
/// contraction has no `m` fragment to load.
///
/// The `(dm, dk, dn)` divisibilities stay, and stay *rule* business: they
/// decide whether the exactly-tiled alternative exists for this shape. They
/// never decide a geometry — that is [`qtile_exact_domain`]'s job — so one
/// column short of a boundary costs the exact alternative and leaves the
/// masked one untouched, which is `qmm_tile_64x64`'s whole point.
fn tile_guard(p: &QParts, dm: u64, dk: u64, dn: u64) -> bool {
    p.m.at_least(2) && p.m.multiple_of(dm) && p.k.multiple_of(dk) && p.n.multiple_of(dn)
}

