fn with_act(b: &mut Builder<'_>, id: Id, node: &Node, want: QAct) -> Option<Id> {
    let Op::L1(l1) = &node.op else { return None };
    let L1::KQContract { act, .. } = l1 else {
        return None;
    };
    if *act == want {
        return None;
    }
    let mut rebuilt = l1.clone();
    if let L1::KQContract { act, .. } = &mut rebuilt {
        *act = want;
    }
    let new = b.add_l1(rebuilt).ok()?;
    b.union(id, new).ok()?;
    Some(new)
}

/// Dequantize the block into registers, then FMA.
pub fn qact_f32(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let _ = f;
    with_act(b, id, node, QAct::F32)
}

/// Pack activations to int8 and dot against still-quantized weights. The
/// reference's hardcoded comment about compounding error becomes a
/// [`NumericContract`] guard: only a value that licenses 8-bit **operands**
/// reaches the int path.
///
/// The guard used to be `RELAXED.allows(..)`, which asks whether the value
/// permits reassociation and FMA contraction. It does not follow. Both of
/// those are exact to rounding; re-encoding the activations onto an int8 grid
/// is not, and the error does not shrink with a wider accumulator. Measured
/// on the `matmul::q_mat_mul_rank1` shape (Q8_0, k = 32): the exact f32 dot
/// is 0.48197886 and the CPU device value under this packing is 0.47361845,
/// bit-identical to the ideal int8-activation dot computed host-side
/// (`scale = max|a| / 127`, round-half-away, clamp, rescale) — 1.7% relative
/// against a case bar of 1e-3. The kernel is right; what was wrong was the
/// permission it was minted under.
///
/// So the guard now names the axis it means. See
/// [`NumericContract::RELAXED_OPERANDS`]: nothing mints that contract yet, so
/// this rule is offered nowhere until a frontend opts a value into it.
pub fn qact_q8_dp4a(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let Op::L1(L1::KQContract { fmt, .. }) = &node.op else {
        return None;
    };
    if !supports_q8_dp4a(*fmt) {
        return None;
    }
    if !NumericContract::RELAXED_OPERANDS.allows(f.own().numeric) {
        return None;
    }
    with_act(b, id, node, QAct::Q8Dp4a)
}

/// Whether a `Pack` operand access is realized by a launch anywhere in the
/// pipeline. It is not, which is why [`qrepack`] declines. See the comment
/// inside it.
const REPACK_HAS_A_LAUNCH: bool = false;

/// Mint the other [`QLayout`] for the weight operand, wrapping the source
/// in a repacking access. Legal for every format in both directions; the
/// cost is the repack bytes — derivable from `fmt` and the two
/// `QFmt::block_bytes` — amortized over `Persistence::Persistent`.
pub fn qrepack(b: &mut Builder<'_>, id: Id, node: &Node, f: &Facts<'_>) -> Option<Id> {
    let _ = f;
    // **Nothing executes the repack yet.** `AccessPlan::Pack { into }` appears
    // in `plan.rs` only in the plan hash and the symbol walk — no launch is
    // derived for it and neither emitter honours it — so the node this rule
    // mints tells the kernel the weight is in `want` while the buffer still
    // holds the original bytes. Selecting it decoded Q4_0/Q5_0 native blocks as
    // if their scales were f32: NaN on the CPU, ~1e-8 on the GPU.
    //
    // The rewrite itself is right; what is missing is a materialization step,
    // because the repacked image is a *new buffer* produced by its own launch —
    // `realize`/`plan` work, not a rewrite.
    // `qrepack_needs_a_repack_launch_that_does_not_exist` pins this boundary
    // and fails the moment one appears.
    if !REPACK_HAS_A_LAUNCH {
        return None;
    }
    let Op::L1(l1) = &node.op else { return None };
    let L1::KQContract { layout, b: weight, .. } = l1 else {
        return None;
    };
    // A repack of a repack is not a second alternative: the edge already
    // carries one packing step and cannot carry two.
    if !matches!(weight.access, AccessPlan::Alias) {
        return None;
    }
    let want = match layout {
        QLayout::Native => QLayout::F32Scales,
        QLayout::F32Scales => QLayout::Native,
    };
    // The repacked buffer is a fresh contiguous byte image of the weight;
    // the `Pack` access is where the repack happens.
    let into = Layout::contiguous(weight.layout.shape());
    let mut rebuilt = l1.clone();
    if let L1::KQContract { layout, b: weight, .. } = &mut rebuilt {
        *layout = want;
        weight.access = AccessPlan::Pack { into };
    }
    let new = b.add_l1(rebuilt).ok()?;
    b.union(id, new).ok()?;
    Some(new)
}

