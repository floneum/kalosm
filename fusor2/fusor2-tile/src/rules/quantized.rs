    /// The int8 activation dot is licensed by an **operand-precision** term,
    /// not by permission to reassociate.
    ///
    /// Both directions, because only one of them is a law about a rule and the
    /// other is a law about the whole default pipeline: under the contract
    /// every value carries today the packing is not offered at all, and it
    /// appears the moment — and only the moment — a value licenses 8-bit
    /// operands. `QAct::F32` is unconditional either way.
    ///
    /// The measured content of the guard: at Q8_0 the packing costs 1.7%
    /// relative on `matmul::q_mat_mul_rank1`, which is not a rounding effect
    /// and does not shrink with a wider accumulator.
    #[test]
    fn q8_dp4a_needs_an_operand_precision_licence() {
        let (fx, c) = build(128, 1024, 8192, QFmt::Q8_0);
        let nodes = qnodes(&fx, c);
        let has = |nodes: &[L1], want: QAct| {
            nodes
                .iter()
                .any(|n| matches!(n, L1::KQContract { act, .. } if *act == want))
        };
        assert!(has(&nodes, QAct::F32), "the f32 path is unconditional");
        assert!(
            !has(&nodes, QAct::Q8Dp4a),
            "RELAXED permits reassociation and FMA contraction, neither of which \
             licenses re-encoding the activations onto an int8 grid"
        );

        let mut fx = Fixture::new(apple_caps());
        fx.graph = fusor2_ir::egraph::EGraph::new(std::sync::Arc::new(LicensesInt8Operands));
        let act = fx.buffer(Dtype::F32, &[128, 1024]);
        let w = fx.quantized(QFmt::Q8_0, QLayout::Native, &[8192, 1024]);
        let c = fx.contract(qspec(), Dtype::F32, act, w);
        assert_eq!(
            fx.graph.facts(c).numeric,
            NumericContract::RELAXED_OPERANDS,
            "the licensing fixture must actually license"
        );
        fx.apply_all(TILE_RULES, c);
        let nodes = qnodes(&fx, c);
        assert!(has(&nodes, QAct::F32));
        assert!(
            has(&nodes, QAct::Q8Dp4a),
            "a licensed value must still reach the int8 dot"
        );
    }

