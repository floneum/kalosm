//! Quantized contraction lowerings, the two activation packings, and
//! `qrepack`.
//!
//! The reference's nine `qmatmul_direct_selector` arms become ten
//! independent rules with divisibility as the only legality guard.
//! `N >= 8192`, `K <= 1024` and `storage >= 32 KiB` become **nothing** here
//! — they are cost terms in W6 — so N = 8191 degrades continuously instead
//! of falling several arms down a first-match list. The `cached: bool`
//! variant flag is dropped: it was a pipeline-cache-slot distinction
//! encoded as a kernel variant, so the two 64x64 rules mint one node and
//! differ only in the format families they are legal for.
//!
//! Both dot lowerings coexist: `QAct::F32` (dequantize the block into
//! registers, then FMA) and `QAct::Q8Dp4a` (`Pack4xI8Clamp` the
//! activations, `Dot4I8Packed` against still-quantized weights — provably
//! not expressible as dequantize-then-dot). They do not coexist
//! *unconditionally*: the int8 packing re-encodes the activations onto a
//! coarser grid, so it is offered only where the value's
//! [`NumericContract`] licenses 8-bit operands. See [`qact_q8_dp4a`].
//!
//! `qrepack` mints the other [`QLayout`] for a weight operand in **both**
//! directions, for every format: the reference's per-device
//! `Q6K => always F32Scales` branch is deleted, so a device that never runs
//! the alignment-sensitive kernel no longer pays +0.9% bytes.
//!
//! **The geometry is a schedule domain, not a rule.** Every one of these
//! rules used to mint a domain holding exactly one point — nine hand-written
//! `(bm, bn)` tiles and one bare [`ScheduleDomain::Point`] — so a quantized
//! matmul reached extraction with no schedule decision left to make. The
//! `(bm, bn)` pairs are now generated by [`crate::domains::quantized`] from
//! lane limits, block divisibility and the exact `SgemmParams::legal`
//! footprint `verify_l1` applies; what survives here is what a *rule* is
//! actually for — which format reaches which family, and whether the shape is
//! tiled exactly or with masked edges.
//!
//! Owned by W4.

